/// shell 单引号转义：把 `'` 换成 `'\''`。
///
/// 模型给的字符串可能含引号、分号、`$`，不转义会直接把命令拆坏
/// （既是 bug 也是注入面）。
///
/// ## 为什么单独一个文件
///
/// 这段转义现在有三处要用：工具层（拼 shell 命令）、对象池的引用解析
/// （把句柄解析成路径塞进命令）、以及 reader 的兜底读取。
/// 各写一份的话迟早会有一处少转义一个字符，而这是安全相关的逻辑 ——
/// 不一致就意味着有一条路能绕过。
///
/// 实现按 POSIX shell 的规则：把整串包在单引号里，内部每个 `'` 变成
/// `'\''`（收尾 → 转义的字面量引号 → 重新开引号）。
String shellQuote(String s) => "'${s.replaceAll("'", r"'\''")}'";

/// 双引号转义：只用于必须用双引号包裹的场景（如 `sed -n '$a,$b p'` 之外的
/// 变量展开）。能不用就不用 —— 单引号才是零歧义的。
String shellQuoteDouble(String s) => '"${s.replaceAll(r'\', r'\\').replaceAll('"', r'\"').replaceAll(r'$', r'\$').replaceAll('`', r'\`')}"';
